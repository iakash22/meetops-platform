import type { EmailAddress, EmailMessage, StorageObjectMetadata } from '@meetops/contracts';
import { createRng, type Rng } from './rng.js';

export type Tenant = { id: string; slug: string; name: string };

export type FactoryContext = {
  readonly seed: number;
  readonly rng: Rng;
  readonly tenant: Tenant;
  /** Fixed clock so dates are reproducible. */
  readonly now: Date;
};

const FIRST = ['ada', 'grace', 'linus', 'margaret', 'alan', 'barbara'] as const;
const SUBJECTS = ['Weekly sync', 'Sprint review', 'Customer call', 'Design crit'] as const;

/**
 * Create a deterministic, tenant-scoped factory set.
 * Same seed + tenant => identical data. Every record is tagged with the tenant
 * so cross-tenant leakage is easy to assert on.
 */
export function createFactories(opts: { seed?: number; tenantSlug?: string; now?: Date } = {}) {
  const seed = opts.seed ?? 42;
  const rng = createRng(seed);
  const slug = opts.tenantSlug ?? 'acme';
  const ctx: FactoryContext = {
    seed,
    rng,
    now: opts.now ?? new Date('2026-01-01T00:00:00.000Z'),
    tenant: { id: rng.id('tnt'), slug, name: `${slug[0]?.toUpperCase() ?? ''}${slug.slice(1)} Inc` }
  };

  const emailAddress = (overrides: Partial<EmailAddress> = {}): EmailAddress => {
    const first = rng.pick(FIRST);
    return { name: first, email: `${first}.${rng.int(1, 999)}@${ctx.tenant.slug}.test`, ...overrides };
  };

  const emailMessage = (overrides: Partial<EmailMessage> = {}): EmailMessage => ({
    from: emailAddress(),
    to: [emailAddress()],
    subject: `[${ctx.tenant.slug}] ${rng.pick(SUBJECTS)}`,
    text: 'Generated by tests/factories',
    ...overrides
  });

  const storageObject = (overrides: Partial<StorageObjectMetadata> = {}): StorageObjectMetadata => {
    const key = `${ctx.tenant.id}/${rng.id('obj')}.bin`;
    return {
      key,
      bucket: 'meetops-test',
      size: rng.int(1, 10_000),
      contentType: 'application/octet-stream',
      createdAt: new Date(ctx.now),
      custom: { tenantId: ctx.tenant.id },
      ...overrides
    };
  };

  return { ctx, tenant: ctx.tenant, emailAddress, emailMessage, storageObject };
}

export type Factories = ReturnType<typeof createFactories>;
