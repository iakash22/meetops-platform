import type { EmailAddress, EmailMessage, StorageObjectMetadata } from '@meetops/contracts';
import { createRng, type Rng } from './rng.js';

/*
 * Shapes follow the @meetops/contracts domain schemas from PR #17 (Organization,
 * Membership, Project, Meeting, FileObject; field `organizationId`). They are typed
 * locally until #17 merges; tests/contract validates factory output against the real
 * schemas whenever the installed contracts package exports them.
 */
export type Role = 'owner' | 'admin' | 'member' | 'viewer';
export type Organization = {
  id: string;
  name: string;
  slug: string;
  createdAt: string;
  updatedAt: string;
};
export type User = {
  id: string;
  email: string;
  name?: string;
  createdAt: string;
  updatedAt: string;
};
export type Membership = {
  id: string;
  organizationId: string;
  userId: string;
  role: Role;
  createdAt: string;
};
export type Project = {
  id: string;
  organizationId: string;
  name: string;
  createdAt: string;
  updatedAt: string;
};
export type Meeting = {
  id: string;
  organizationId: string;
  projectId?: string;
  title: string;
  source: 'upload' | 'extension' | 'desktop' | 'bot';
  status: 'scheduled' | 'recording' | 'processing' | 'completed' | 'failed';
  createdById: string;
  createdAt: string;
  updatedAt: string;
};
export type FileObject = {
  id: string;
  organizationId: string;
  provider: string;
  bucket: string;
  key: string;
  mimeType: string;
  sizeBytes: number;
  createdAt: string;
};

export type FactoryContext = {
  readonly seed: number;
  readonly rng: Rng;
  readonly organization: Organization;
  /** Fixed clock so dates are reproducible. */
  readonly now: Date;
};

const FIRST = ['ada', 'grace', 'linus', 'margaret', 'alan', 'barbara'] as const;
const SUBJECTS = ['Weekly sync', 'Sprint review', 'Customer call', 'Design crit'] as const;

/**
 * Create a deterministic, organization-scoped factory set.
 * Same seed + organization slug => identical data. Every record carries the
 * organizationId so cross-organization leakage is easy to assert on.
 */
export function createFactories(
  opts: { seed?: number; organizationSlug?: string; now?: Date } = {},
) {
  const seed = opts.seed ?? 42;
  const rng = createRng(seed);
  const slug = opts.organizationSlug ?? 'acme';
  const now = opts.now ?? new Date('2026-01-01T00:00:00.000Z');
  const iso = now.toISOString();
  const organization: Organization = {
    id: rng.uuid(),
    slug,
    name: `${slug[0]?.toUpperCase() ?? ''}${slug.slice(1)} Inc`,
    createdAt: iso,
    updatedAt: iso,
  };
  const ctx: FactoryContext = { seed, rng, now, organization };
  const organizationId = organization.id;

  const user = (o: Partial<User> = {}): User => {
    const first = rng.pick(FIRST);
    return {
      id: rng.uuid(),
      email: `${first}.${rng.int(1, 999)}@${slug}.test`,
      name: first,
      createdAt: iso,
      updatedAt: iso,
      ...o,
    };
  };
  const membership = (o: Partial<Membership> = {}): Membership => ({
    id: rng.uuid(),
    organizationId,
    userId: o.userId ?? user().id,
    role: 'member',
    createdAt: iso,
    ...o,
  });
  const project = (o: Partial<Project> = {}): Project => ({
    id: rng.uuid(),
    organizationId,
    name: `Project ${rng.int(1, 99)}`,
    createdAt: iso,
    updatedAt: iso,
    ...o,
  });
  const meeting = (o: Partial<Meeting> = {}): Meeting => ({
    id: rng.uuid(),
    organizationId,
    title: `[${slug}] ${rng.pick(SUBJECTS)}`,
    source: 'upload',
    status: 'scheduled',
    createdById: o.createdById ?? user().id,
    createdAt: iso,
    updatedAt: iso,
    ...o,
  });
  const fileObject = (o: Partial<FileObject> = {}): FileObject => {
    const id = rng.uuid();
    return {
      id,
      organizationId,
      provider: 'local',
      bucket: 'meetops-test',
      key: `org/${organizationId}/files/${id}.bin`,
      mimeType: 'application/octet-stream',
      sizeBytes: rng.int(1, 10_000),
      createdAt: iso,
      ...o,
    };
  };

  // Phase 0 legacy contract types (still exported by @meetops/contracts).
  const emailAddress = (o: Partial<EmailAddress> = {}): EmailAddress => {
    const first = rng.pick(FIRST);
    return { name: first, email: `${first}.${rng.int(1, 999)}@${slug}.test`, ...o };
  };
  const emailMessage = (o: Partial<EmailMessage> = {}): EmailMessage => ({
    from: emailAddress(),
    to: [emailAddress()],
    subject: `[${slug}] ${rng.pick(SUBJECTS)}`,
    text: 'Generated by tests/factories',
    ...o,
  });
  const storageObject = (o: Partial<StorageObjectMetadata> = {}): StorageObjectMetadata => ({
    key: `org/${organizationId}/${rng.uuid()}.bin`,
    bucket: 'meetops-test',
    size: rng.int(1, 10_000),
    contentType: 'application/octet-stream',
    createdAt: new Date(now),
    custom: { organizationId },
    ...o,
  });

  return {
    ctx,
    organization,
    user,
    membership,
    project,
    meeting,
    fileObject,
    emailAddress,
    emailMessage,
    storageObject,
  };
}

export type Factories = ReturnType<typeof createFactories>;
