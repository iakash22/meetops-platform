import { Type, type Static } from '@sinclair/typebox';
import { Id, IsoDateTime, SafeDisplayText } from '../common.js';
import {
  DESKTOP_SCOPES,
  DESKTOP_TOKEN_AUDIENCE,
  DESKTOP_TOKEN_TTL_SECONDS,
  DESKTOP_TOKEN_TYPE,
} from '../constants.js';

export {
  DESKTOP_AUTH_PATHS,
  DESKTOP_AUTHORIZATION_CODE_TTL_SECONDS,
  DESKTOP_REFRESH_FAMILY_MAX_LIFETIME_SECONDS,
  DESKTOP_SCOPES,
  DESKTOP_TOKEN_AUDIENCE,
  DESKTOP_TOKEN_TTL_SECONDS,
  DESKTOP_TOKEN_TYPE,
} from '../constants.js';

/**
 * v0.9.0: desktop (Tauri) sign-in, ADR-012 Option A (system browser, authorization code + PKCE S256, loopback
 * redirect). ADR-012 is still Proposed; servers keep these routes off until it is Accepted.
 */
export const DesktopScope = Type.Union(DESKTOP_SCOPES.map((s) => Type.Literal(s)));
export type DesktopScope = (typeof DESKTOP_SCOPES)[number];

const strict = { additionalProperties: false } as const;

/** Per-install device id (UUID), generated by the app and kept in the keychain item's metadata. */
export const DesktopDeviceId = Id;
export const DesktopDeviceLabel = SafeDisplayText({ maxLength: 100 });
/** RFC 7636 S256 challenge: base64url(SHA-256(verifier)), always 43 characters. */
export const PkceCodeChallenge = Type.String({
  minLength: 43,
  maxLength: 43,
  pattern: '^[A-Za-z0-9_-]{43}$',
});
/** RFC 7636 verifier: 43 to 128 unreserved characters. ADR-012 uses 32 random bytes (43 base64url chars). */
export const PkceCodeVerifier = Type.String({
  minLength: 43,
  maxLength: 128,
  pattern: '^[A-Za-z0-9._~-]{43,128}$',
});
/**
 * ADR-012 section 1.5: exactly `http://127.0.0.1:<port>/callback` (RFC 8252 section 7.3, any port 1024-65535), with no
 * query, fragment or userinfo. Servers MUST also check it exactly; this pattern is the first line only.
 */
export const DesktopRedirectUri = Type.String({
  maxLength: 40,
  pattern:
    '^http://127\\.0\\.0\\.1:(102[4-9]|10[3-9][0-9]|1[1-9][0-9]{2}|[2-9][0-9]{3}|[1-5][0-9]{4}|6[0-4][0-9]{3}|65[0-4][0-9]{2}|655[0-2][0-9]|6553[0-5])/callback$',
});
/** Single-use authorization code: 43 to 128 base64url characters (256-bit). */
export const DesktopAuthorizationCode = Type.String({
  minLength: 43,
  maxLength: 128,
  pattern: '^[A-Za-z0-9_-]+$',
});
const AccessToken = Type.String({ minLength: 32, maxLength: 512 });
const RefreshToken = Type.String({ minLength: 32, maxLength: 512 });

/**
 * POST /auth/desktop/authorize, from the web `/desktop/authorize` page after the user confirms user, org and device.
 * Requires the `__Host-` session cookie and `x-csrf-token`. Carries no tokens.
 */
export const DesktopAuthorizeRequest = Type.Object(
  {
    codeChallenge: PkceCodeChallenge,
    codeChallengeMethod: Type.Literal('S256'),
    redirectUri: DesktopRedirectUri,
    deviceId: DesktopDeviceId,
    deviceLabel: Type.Optional(DesktopDeviceLabel),
  },
  strict,
);
export type DesktopAuthorizeRequest = Static<typeof DesktopAuthorizeRequest>;
/** The page then redirects to `redirectUri?code=<authorizationCode>&state=<state>`. Code expires in <= 60 s. */
export const DesktopAuthorizeResponse = Type.Object(
  {
    authorizationCode: DesktopAuthorizationCode,
    expiresAt: IsoDateTime,
    organizationId: Id,
    organizationName: SafeDisplayText({ maxLength: 200, trimmed: true }),
  },
  strict,
);
export type DesktopAuthorizeResponse = Static<typeof DesktopAuthorizeResponse>;

/** POST /auth/desktop/token (no cookie). The code is consumed on any attempt, including a mismatch. */
export const DesktopTokenRequest = Type.Object(
  {
    authorizationCode: DesktopAuthorizationCode,
    codeVerifier: PkceCodeVerifier,
    redirectUri: DesktopRedirectUri,
    deviceId: DesktopDeviceId,
  },
  strict,
);
export type DesktopTokenRequest = Static<typeof DesktopTokenRequest>;

const tokenPair = {
  accessToken: AccessToken,
  refreshToken: RefreshToken,
  tokenType: Type.Literal(DESKTOP_TOKEN_TYPE),
  audience: Type.Literal(DESKTOP_TOKEN_AUDIENCE),
  expiresAt: IsoDateTime,
  expiresIn: Type.Integer({ minimum: 1, maximum: DESKTOP_TOKEN_TTL_SECONDS }),
  refreshExpiresAt: IsoDateTime,
  organizationId: Id,
  scopes: Type.Array(DesktopScope, {
    minItems: 1,
    maxItems: DESKTOP_SCOPES.length,
    uniqueItems: true,
  }),
};

/**
 * Token-bearing response (ADR-012 amends ADR-005 A1.2.5: only extension and desktop token responses carry tokens).
 * The refresh token goes to the OS keychain from Rust only; neither token crosses into the webview.
 */
export const DesktopTokenResponse = Type.Object(tokenPair, strict);
export type DesktopTokenResponse = Static<typeof DesktopTokenResponse>;

/** POST /auth/desktop/refresh: rotates; reuse of a consumed refresh token revokes the family. */
export const DesktopRefreshRequest = Type.Object(
  { deviceId: DesktopDeviceId, refreshToken: RefreshToken },
  strict,
);
export type DesktopRefreshRequest = Static<typeof DesktopRefreshRequest>;
export const DesktopRefreshResponse = Type.Object(tokenPair, strict);
export type DesktopRefreshResponse = Static<typeof DesktopRefreshResponse>;

/** POST /auth/desktop/revoke: idempotent; works after the access token expired. */
export const DesktopRevokeRequest = Type.Object(
  { deviceId: DesktopDeviceId, refreshToken: RefreshToken },
  strict,
);
export type DesktopRevokeRequest = Static<typeof DesktopRevokeRequest>;
export const DesktopRevokeResponse = Type.Object({ revoked: Type.Literal(true) }, strict);
export type DesktopRevokeResponse = Static<typeof DesktopRevokeResponse>;

/**
 * POST /auth/desktop/switch-org: checks a live membership in the target org (else NOT_FOUND, ADR-004), revokes the old
 * family (`org_switch`) and issues a new family for the target org. No browser round trip.
 */
export const DesktopSwitchOrgRequest = Type.Object(
  { deviceId: DesktopDeviceId, refreshToken: RefreshToken, organizationId: Id },
  strict,
);
export type DesktopSwitchOrgRequest = Static<typeof DesktopSwitchOrgRequest>;
export const DesktopSwitchOrgResponse = Type.Object(tokenPair, strict);
export type DesktopSwitchOrgResponse = Static<typeof DesktopSwitchOrgResponse>;
