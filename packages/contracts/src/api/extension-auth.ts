import { Type, type Static } from '@sinclair/typebox';
import { Id, IsoDateTime, SafeDisplayText } from '../common.js';

import {
  EXTENSION_SCOPES, EXTENSION_TOKEN_AUDIENCE, EXTENSION_TOKEN_TTL_SECONDS, EXTENSION_TOKEN_TYPE, PAIRING_CODE_MESSAGE_TYPE,
} from '../constants.js';

export {
  EXTENSION_AUTH_PATHS, EXTENSION_REFRESH_FAMILY_MAX_LIFETIME_SECONDS, EXTENSION_SCOPES, EXTENSION_TOKEN_AUDIENCE,
  EXTENSION_TOKEN_TTL_SECONDS, EXTENSION_TOKEN_TYPE, PAIRING_CODE_MESSAGE_TYPE, REDACT_KEYS,
} from '../constants.js';
export const ExtensionScope = Type.Union(EXTENSION_SCOPES.map((s) => Type.Literal(s)));
export type ExtensionScope = (typeof EXTENSION_SCOPES)[number];

const strict = { additionalProperties: false } as const;

/** Chrome extension id: 32 characters in a-p. The server checks it against an allowlist. */
const ExtensionId = Type.String({ pattern: '^[a-p]{32}$' });
/** Single-use client nonce, generated by the extension on a user gesture: 32 to 128 base64url characters. */
export const ExtensionNonce = Type.String({ minLength: 32, maxLength: 128, pattern: '^[A-Za-z0-9_-]{32,128}$' });
/** Stable per-install device id (UUID), generated by the extension. */
export const ExtensionDeviceId = Id;
/**
 * Printable only: no C0/C1 control characters, DEL, line/paragraph separators, HTML-significant characters
 * (`<`, `>`, `"`, `'`, `&`), or bidi/format characters
 * (U+200B-U+200F, U+202A-U+202E, U+2060, U+2066-U+2069, U+FEFF, U+061C). Uses the shared SafeDisplayText charset.
 */
export const ExtensionDeviceLabel = SafeDisplayText({ maxLength: 100 });
/** Single-use pairing code: 32 to 128 base64url characters. */
export const ExtensionPairingCode = Type.String({ minLength: 32, maxLength: 128, pattern: '^[A-Za-z0-9_-]+$' });
const AccessToken = Type.String({ minLength: 32, maxLength: 512 });
const RefreshToken = Type.String({ minLength: 32, maxLength: 512 });

/**
 * POST /auth/extension/pair, from the web app after the user confirms the org on the pairing page. Requires the `__Host-`
 * session cookie and `x-csrf-token`; `extensionId` must be allowlisted. The nonce was created by the extension on a
 * user gesture and handed to the page over `externally_connectable` messaging.
 */
export const ExtensionPairRequest = Type.Object(
  { extensionId: ExtensionId, deviceId: ExtensionDeviceId, nonce: ExtensionNonce, deviceLabel: Type.Optional(ExtensionDeviceLabel) },
  strict,
);
export type ExtensionPairRequest = Static<typeof ExtensionPairRequest>;
/** Carries no tokens. `pairingCode` is single-use, bound to (nonce, extensionId, deviceId, user, org) and expires in ≤60 s. */
export const ExtensionPairResponse = Type.Object(
  { pairingCode: ExtensionPairingCode, expiresAt: IsoDateTime, organizationId: Id, organizationName: Type.String({ minLength: 1, maxLength: 200 }) },
  strict,
);
export type ExtensionPairResponse = Static<typeof ExtensionPairResponse>;

/**
 * Pairing handoff: the message the web pairing page sends to the extension over `externally_connectable` messaging
 * after `POST /auth/extension/pair`. The extension MUST validate it, and MUST check that `nonce` equals the nonce it
 * generated, before calling `POST /auth/extension-token`. It carries no tokens.
 */
export const PairingCodeMessage = Type.Object(
  { type: Type.Literal(PAIRING_CODE_MESSAGE_TYPE), pairingCode: ExtensionPairingCode, nonce: ExtensionNonce },
  strict,
);
export type PairingCodeMessage = Static<typeof PairingCodeMessage>;

/** POST /auth/extension-token, from the extension (no cookie). The nonce must match the one bound to the pairing code. */
export const ExtensionTokenRequest = Type.Object(
  { extensionId: ExtensionId, deviceId: ExtensionDeviceId, pairingCode: ExtensionPairingCode, nonce: ExtensionNonce },
  strict,
);
export type ExtensionTokenRequest = Static<typeof ExtensionTokenRequest>;

const tokenPair = {
  accessToken: AccessToken,
  refreshToken: RefreshToken,
  tokenType: Type.Literal(EXTENSION_TOKEN_TYPE),
  audience: Type.Literal(EXTENSION_TOKEN_AUDIENCE),
  expiresAt: IsoDateTime,
  expiresIn: Type.Integer({ minimum: 1, maximum: EXTENSION_TOKEN_TTL_SECONDS }),
  refreshExpiresAt: IsoDateTime,
  organizationId: Id,
  scopes: Type.Array(ExtensionScope, { minItems: 1, maxItems: EXTENSION_SCOPES.length, uniqueItems: true }),
};

/**
 * **One of the only two response bodies in the API that carry tokens** (with `ExtensionRefreshResponse`, ADR-005).
 * Opaque random tokens; the server stores only SHA-256 hashes. `nonce` echoes the request nonce, and the extension
 * must reject a response whose nonce does not match the one it stored. Stored in `chrome.storage.session` only.
 */
export const ExtensionTokenResponse = Type.Object({ ...tokenPair, nonce: ExtensionNonce }, strict);
export type ExtensionTokenResponse = Static<typeof ExtensionTokenResponse>;

/**
 * POST /auth/extension/refresh (no cookie, no Bearer: it runs with an expired access token). Authenticated only by the
 * `refreshToken` in the body, bound to `extensionId` and `deviceId`. Rotates: the old refresh token is consumed; reuse revokes the family.
 */
export const ExtensionRefreshRequest = Type.Object(
  { extensionId: ExtensionId, deviceId: ExtensionDeviceId, refreshToken: RefreshToken },
  strict,
);
export type ExtensionRefreshRequest = Static<typeof ExtensionRefreshRequest>;
/** `refreshExpiresAt` never exceeds the family's pairing time + EXTENSION_REFRESH_FAMILY_MAX_LIFETIME_SECONDS. */
export const ExtensionRefreshResponse = Type.Object(tokenPair, strict);
export type ExtensionRefreshResponse = Static<typeof ExtensionRefreshResponse>;

/**
 * POST /auth/extension/revoke (no cookie, no Bearer). Authenticated only by the required `refreshToken` in the body, bound
 * to `extensionId` and `deviceId`, so it also works after the access token has expired. Revokes the device's whole
 * refresh family. Idempotent.
 */
export const ExtensionRevokeRequest = Type.Object(
  { extensionId: ExtensionId, deviceId: ExtensionDeviceId, refreshToken: RefreshToken },
  strict,
);
export type ExtensionRevokeRequest = Static<typeof ExtensionRevokeRequest>;
export const ExtensionRevokeResponse = Type.Object({ revoked: Type.Literal(true) }, strict);
export type ExtensionRevokeResponse = Static<typeof ExtensionRevokeResponse>;
